--   Этот же ключ не даст выполнить перенос повторно — дубли будут отклонены.
--
-- Какое действие в скрипте разворачивает список позиций?
--   string_to_table(r.items, ';'), вызванная через CROSS JOIN LATERAL: для каждой
--   строки raw_deliveries она возвращает столько строк, сколько позиций в items,
--   и каждая позиция остаётся связана со своим поступлением. Затем split_part
--   выделяет из позиции поля по разделителю «|», а ::integer и ::numeric(10, 2)
--   приводят текст к нужным типам.

