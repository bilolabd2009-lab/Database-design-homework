-- =====================================================================
-- 1. Исходные строки и разделители
-- =====================================================================
SELECT delivery_id, supplier_name, items
FROM raw_deliveries
ORDER BY delivery_id;

-- «;» отделяет одну позицию поступления от другой (список позиций),
-- «|» отделяет поля внутри одной позиции:
--     номер товара | название | количество | цена за единицу.

-- Промежуточный просмотр: список позиций превращается в строки
SELECT r.delivery_id, p.item
FROM raw_deliveries AS r
CROSS JOIN LATERAL
    string_to_table(r.items, ';') AS p(item)
ORDER BY r.delivery_id;

-- =====================================================================
-- 2. Автоматический перенос в 1НФ (один INSERT INTO ... SELECT)
-- =====================================================================
INSERT INTO delivery_lines_1nf
    (delivery_id, supplier_name, product_id, product_title, quantity, unit_price)
SELECT
    r.delivery_id,                                              -- из исходной строки
    r.supplier_name,                                            -- из исходной строки
    trim(split_part(p.item, '|', 1))::integer         AS product_id,
    trim(split_part(p.item, '|', 2))                  AS product_title,
    trim(split_part(p.item, '|', 3))::integer         AS quantity,
    trim(split_part(p.item, '|', 4))::numeric(10, 2)  AS unit_price
FROM raw_deliveries AS r
CROSS JOIN LATERAL
    string_to_table(r.items, ';') AS p(item)
WHERE trim(p.item) <> '';   -- защита от пустой позиции, если список кончается на «;»

-- =====================================================================
-- 3. Проверочная выборка 1: весь результат (ожидается 5 строк)
-- =====================================================================
SELECT delivery_id, product_id, product_title, quantity, unit_price
FROM delivery_lines_1nf
ORDER BY delivery_id, product_id;

-- Ожидаемо:
--  5001 | 201 | Тетрадь | 10 |  45.50
--  5001 | 202 | Ручка   | 20 |  30.00
--  5002 | 201 | Тетрадь |  5 |  44.00
--  5002 | 203 | Папка   |  8 | 120.00
--  5003 | 202 | Ручка   | 12 |  29.50

-- =====================================================================
-- 4. Проверочная выборка 2: все поступления товара 201
-- =====================================================================
SELECT delivery_id, supplier_name, product_title, quantity, unit_price
FROM delivery_lines_1nf
WHERE product_id = 201
ORDER BY delivery_id;

-- Ожидаемо две строки: 5001 (Север) — 10 по 45.50, 5002 (Вектор) — 5 по 44.00.
-- Цены одного товара в разных поступлениях различаются — это допустимо,
-- потому что цена относится к паре «поступление + товар», а не к товару.

-- Исходные данные не тронуты (ожидается 3 строки)
