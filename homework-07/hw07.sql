-- =====================================================================
-- 1. INNER JOIN (ожидается 4 строки)
-- =====================================================================
-- Только сотрудники с назначенным отделом: Глеба нет, «Аналитики» нет.
SELECT e.employee_id,
       e.employee_name,
       d.department_id,
       d.department_name
FROM employees AS e
INNER JOIN departments AS d
        ON e.department_id = d.department_id
ORDER BY e.employee_id;

--  1 | Анна  | 1 | Разработка
--  2 | Борис | 1 | Разработка
--  3 | Вера  | 2 | Дизайн
--  5 | Дина  | 3 | Поддержка

-- =====================================================================
-- 2. LEFT JOIN, employees слева (ожидается 5 строк)
-- =====================================================================
-- Все сотрудники, включая Глеба; у него название отдела NULL.
SELECT e.employee_id,
       e.employee_name,
       d.department_name
FROM employees AS e
LEFT JOIN departments AS d
       ON e.department_id = d.department_id
ORDER BY e.employee_id;

-- NULL у Глеба: его department_id пуст, поэтому в departments не нашлось
-- пары. LEFT JOIN всё равно сохраняет строку из левой таблицы, а столбцы
-- правой таблицы заполняет NULL. Это значит «отдела нет», а не «отдел без названия».

-- =====================================================================
-- 3. RIGHT JOIN, employees слева, departments справа (ожидается 5 строк)
-- =====================================================================
-- Все отделы с их сотрудниками, включая пустую «Аналитику»; Глеба нет.
SELECT d.department_id,
       d.department_name,
       e.employee_id,
       e.employee_name
FROM employees AS e
RIGHT JOIN departments AS d
        ON e.department_id = d.department_id
ORDER BY d.department_id, e.employee_id;

--  1 | Разработка | 1    | Анна
--  1 | Разработка | 2    | Борис
--  2 | Дизайн     | 3    | Вера
--  3 | Поддержка  | 5    | Дина
--  4 | Аналитика  | NULL | NULL

-- =====================================================================
-- 4. FULL JOIN (ожидается 6 строк)
-- =====================================================================
-- Все пары плюс непарные строки с обеих сторон: и Глеб, и «Аналитика».
SELECT e.employee_id,
       e.employee_name,
       d.department_id,
       d.department_name
FROM employees AS e
FULL JOIN departments AS d
       ON e.department_id = d.department_id
ORDER BY d.department_id NULLS LAST, e.employee_id;

-- Два случая отсутствующего соответствия:
--  а) Глеб: сотрудник без отдела, у него пусты столбцы отдела (d.department_id, d.department_name);
--  б) «Аналитика»: отдел без сотрудников, у неё пусты столбцы сотрудника (e.employee_id, e.employee_name).
-- 4 совпавшие пары + 1 сотрудник без отдела + 1 отдел без сотрудников = 6 строк.

-- =====================================================================
-- 5. LEFT JOIN + IS NULL: отделы без сотрудников (ожидается 1 строка)
-- =====================================================================
-- Остаются только отделы, к которым не нашлось ни одного сотрудника — «Аналитика».
SELECT d.department_id,
       d.department_name
FROM departments AS d
LEFT JOIN employees AS e
       ON e.department_id = d.department_id
WHERE e.employee_id IS NULL
ORDER BY d.department_id;

-- Проверяем именно e.employee_id: это первичный ключ, у реального сотрудника
-- он никогда не бывает NULL, значит NULL здесь означает «пары не нашлось».

-- =====================================================================
-- 6. CROSS JOIN (ожидается 20 строк)
-- =====================================================================
-- Каждый сотрудник в паре с каждым отделом: 5 × 4 = 20 вариантов.
SELECT e.employee_name,
       d.department_name
FROM employees AS e
CROSS JOIN departments AS d
ORDER BY e.employee_name, d.department_name;

-- Условие соединения здесь нет: берутся все сочетания, а не фактические связи.
-- Поэтому каждая строка — это возможный вариант «сотрудника X можно поставить
-- в отдел Y», из которых потом выбирают подходящее распределение.

-- =====================================================================
-- Самопроверка: почему «Разработка» встречается несколько раз
-- =====================================================================
-- Соединение выдаёт по строке на каждую найденную пару. В «Разработке» два
-- сотрудника (Анна и Борис), значит у одной строки отдела две пары и две строки
-- результата. Отдел не дублируется в таблице departments — он повторяется
-- только в результате, по одному разу на каждого своего сотрудника.

-- =====================================================================
-- Дополнительно: SELF JOIN (ожидается 5 строк)
-- =====================================================================
-- Каждый сотрудник и имя его наставника; у Анны и Глеба наставника нет (NULL).
SELECT e.employee_id,
       e.employee_name,
       m.employee_name AS mentor_name
FROM employees AS e
LEFT JOIN employees AS m
       ON e.mentor_id = m.employee_id
ORDER BY e.employee_id;

--  1 | Анна  | NULL
--  2 | Борис | Анна
--  3 | Вера  | Анна
--  4 | Глеб  | NULL
--  5 | Дина  | Вера

-- =====================================================================
-- Ответы
-- =====================================================================
-- LEFT JOIN сохраняет все строки левой таблицы, RIGHT JOIN — все строки правой;
-- у строк без пары столбцы другой стороны заполняются NULL.
-- FULL JOIN добавляет к совпавшим парам непарные строки с обеих сторон:
-- здесь это Глеб (сотрудник без отдела) и «Аналитика» (отдел без сотрудников).
-- CROSS JOIN даёт 20 строк, потому что соединяет каждую из 5 строк employees
-- с каждой из 4 строк departments без условия: 5 × 4 = 20.

